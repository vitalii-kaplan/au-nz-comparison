#!/usr/bin/env python3
"""Generate the denominator-sensitivity tables and figure used by the article."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("module") != "src.analysis_10_sensitivity" or value.get("status") != "passed":
        raise ValueError(f"{path}: sensitivity analysis did not pass")
    for output in value["outputs"]:
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]:
            raise ValueError(f"{path}: output hash mismatch for {target}")


def error_coordinates(
    source: list[dict[str, str]],
    x: str,
    estimate: str,
    lower: str,
    upper: str,
    scale: float = 1.0,
) -> str:
    output = []
    for row in source:
        value = float(row[estimate]) * scale
        low = float(row[lower]) * scale
        high = float(row[upper]) * scale
        output.append(
            f"({row[x]},{value:.12g}) += (0,{high-value:.12g}) -= (0,{value-low:.12g})"
        )
    return " ".join(output)


def generate_outputs(
    *,
    robustness_dir: Path = ROOT / "data/results/robustness",
    manifest_dir: Path = ROOT / "data/results/manifests",
    table_dir: Path = ROOT / "article/tables",
    figure_dir: Path = ROOT / "article/figures",
) -> dict[str, Path]:
    verify_manifest(manifest_dir / "10_sensitivity.json")
    sensitivity = rows(robustness_dir / "sensitivity_analysis_summary.csv")
    counts = rows(robustness_dir / "threshold_population_counts.csv")
    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "table": table_dir / "sensitivity_analysis.tex",
        "figure": figure_dir / "threshold_sensitivity.tex",
    }

    by_key = {
        (row["threshold_min_decisions_each"], row["method"]): row
        for row in sensitivity
    }
    paired_lines = [
        "% Generated by scripts/generate_article_sensitivity_outputs.py. Do not edit.",
        r"\begin{table}[H]",
        r"\caption{Sensitivity of paired differences to minimum decision denominators}",
        r"\label{tab:sensitivity-paired}",
        r"\centering",
        r"\small",
        r"\begin{tabular}{rrrrrr}",
        r"\toprule",
        r"Minimum & Origins & \shortstack{Mean difference, pp\\(95\% CI)} & \shortstack{Median difference, pp\\(95\% CI)} & \shortstack{AU\\decisions} & \shortstack{NZ\\decisions} \\",
        r"\midrule",
    ]
    for count in counts:
        threshold = count["threshold_min_decisions_each"]
        mean = by_key[(threshold, "Paired t-test")]
        median = by_key[(threshold, "Wilcoxon signed-rank")]
        paired_lines.append(
            f"{threshold} & {count['included_pairs']} & "
            f"{float(mean['effect_estimate'])*100:.1f} ({float(mean['ci_lower'])*100:.1f}, {float(mean['ci_upper'])*100:.1f}) & "
            f"{float(median['effect_estimate'])*100:.1f} ({float(median['ci_lower'])*100:.1f}, {float(median['ci_upper'])*100:.1f}) & "
            f"{int(count['included_au_decisions']):,} & {int(count['included_nz_decisions']):,} "
            + r"\\"
        )
    paired_lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\parbox{0.94\textwidth}{\scriptsize Notes: Threshold 0 includes every pooled matched origin. All displayed mean and median intervals exclude zero. Differences are Australia minus New Zealand.}",
        r"\end{table}",
    ]

    concordance_lines = [
        r"\begin{table}[H]",
        r"\caption{Sensitivity of approval-rate concordance to minimum decision denominators}",
        r"\label{tab:sensitivity-concordance}",
        r"\centering",
        r"\small",
        r"\begin{tabular*}{0.94\textwidth}{@{\extracolsep{\fill}}rrrr@{}}",
        r"\toprule",
        r"Minimum & Origins & Pearson $r$ (95\% CI) & Spearman $\rho$ (95\% CI) \\",
        r"\midrule",
    ]
    for count in counts:
        threshold = count["threshold_min_decisions_each"]
        pearson = by_key[(threshold, "Pearson correlation")]
        spearman = by_key[(threshold, "Spearman correlation")]
        concordance_lines.append(
            f"{threshold} & {count['included_pairs']} & "
            f"{float(pearson['effect_estimate']):.3f} ({float(pearson['ci_lower']):.3f}, {float(pearson['ci_upper']):.3f}) & "
            f"{float(spearman['effect_estimate']):.3f} ({float(spearman['ci_lower']):.3f}, {float(spearman['ci_upper']):.3f}) "
            + r"\\"
        )
    concordance_lines += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\parbox{0.94\textwidth}{\scriptsize Notes: All correlation intervals exclude zero.}",
        r"\end{table}",
    ]
    outputs["table"].write_text(
        "\n".join(paired_lines + [r"\medskip"] + concordance_lines) + "\n",
        encoding="utf-8",
    )

    means = [row for row in sensitivity if row["method"] == "Paired t-test"]
    medians = [row for row in sensitivity if row["method"] == "Wilcoxon signed-rank"]
    pearsons = [row for row in sensitivity if row["method"] == "Pearson correlation"]
    spearmans = [row for row in sensitivity if row["method"] == "Spearman correlation"]
    ticks = ",".join(row["threshold_min_decisions_each"] for row in counts)
    figure = rf"""% Generated by scripts/generate_article_sensitivity_outputs.py. Do not edit.
\begin{{minipage}}[t]{{0.49\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{axis}}[width=0.96\linewidth,height=5.7cm,xtick={{{ticks}}},xlabel={{Minimum decisions in each destination}},ylabel={{Difference (percentage points)}},title={{(a) Paired differences}},ymajorgrids=true,legend style={{font=\tiny,draw=none,at={{(0.97,0.97)}},anchor=north east}},label style={{font=\scriptsize}},title style={{font=\small}},tick label style={{font=\scriptsize}}]
\addplot+[blue!80!black,thick,mark=*,error bars/.cd,y dir=both,y explicit] coordinates {{{error_coordinates(means, 'threshold_min_decisions_each', 'effect_estimate', 'ci_lower', 'ci_upper', 100)}}};\addlegendentry{{Mean}}
\addplot+[red!80!black,thick,mark=square*,error bars/.cd,y dir=both,y explicit] coordinates {{{error_coordinates(medians, 'threshold_min_decisions_each', 'effect_estimate', 'ci_lower', 'ci_upper', 100)}}};\addlegendentry{{Median}}
\end{{axis}}
\end{{tikzpicture}}
\end{{minipage}}%
\hfill
\begin{{minipage}}[t]{{0.49\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{axis}}[width=0.96\linewidth,height=5.7cm,xtick={{{ticks}}},xlabel={{Minimum decisions in each destination}},ylabel={{Correlation}},title={{(b) Concordance}},ymin=0.25,ymax=0.95,ymajorgrids=true,legend style={{font=\tiny,draw=none,at={{(0.97,0.03)}},anchor=south east}},label style={{font=\scriptsize}},title style={{font=\small}},tick label style={{font=\scriptsize}}]
\addplot+[blue!80!black,thick,mark=*,error bars/.cd,y dir=both,y explicit] coordinates {{{error_coordinates(pearsons, 'threshold_min_decisions_each', 'effect_estimate', 'ci_lower', 'ci_upper')}}};\addlegendentry{{Pearson}}
\addplot+[red!80!black,thick,mark=square*,error bars/.cd,y dir=both,y explicit] coordinates {{{error_coordinates(spearmans, 'threshold_min_decisions_each', 'effect_estimate', 'ci_lower', 'ci_upper')}}};\addlegendentry{{Spearman}}
\end{{axis}}
\end{{tikzpicture}}
\end{{minipage}}
"""
    outputs["figure"].write_text(figure, encoding="utf-8")
    return outputs


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    outputs = generate_outputs()
    print("Article sensitivity outputs written:")
    for path in outputs.values():
        print(f"- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
