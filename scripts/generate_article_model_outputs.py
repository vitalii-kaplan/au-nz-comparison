#!/usr/bin/env python3
"""Generate the pooled model table and figure used by the article."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if (
        value.get("module") != "src.analysis_07_binomial_regression"
        or value.get("status") != "passed"
    ):
        raise ValueError(f"{path}: pooled-model analysis did not pass")
    for output in value["outputs"]:
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]:
            raise ValueError(f"{path}: output hash mismatch for {target}")


def p_format(value: str) -> str:
    number = float(value)
    return "$p<0.001$" if number < 0.001 else f"$p={number:.3f}$"


def generate_outputs(
    *,
    model_dir: Path = ROOT / "data/results/models",
    manifest_dir: Path = ROOT / "data/results/manifests",
    table_dir: Path = ROOT / "article/tables",
    figure_dir: Path = ROOT / "article/figures",
) -> dict[str, Path]:
    verify_manifest(manifest_dir / "07_binomial_regression.json")
    model = "pooled_country_fixed_effects"
    coefficient = next(
        row
        for row in rows(model_dir / "binomial_model_coefficients.csv")
        if row["model"] == model and row["term"] == "destinationAU"
    )
    contrast = next(
        row
        for row in rows(model_dir / "destination_probability_contrasts.csv")
        if row["model"] == model
    )
    fit = next(
        row
        for row in rows(model_dir / "model_fit_statistics.csv")
        if row["model"] == model
    )
    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "table": table_dir / "pooled_binomial_regression_results.tex",
        "figure": figure_dir / "pooled_standardized_probabilities.tex",
    }

    table = rf"""% Generated by scripts/generate_article_model_outputs.py. Do not edit.
\begin{{table}}
\caption{{Pooled origin-adjusted destination association, 2022--2025}}
\label{{tab:pooled-binomial-regression}}
\centering
\small
\begin{{tabular}}{{lr}}
\toprule
Quantity & Result \\
\midrule
Retained matched origins & {int(fit['countries'])} \\
Recorded decisions & {int(fit['decisions']):,} \\
Australian destination coefficient & {float(coefficient['estimate']):.3f} \\
Cluster-robust standard error & {float(coefficient['standard_error']):.3f} \\
Odds ratio (95\% CI) & {float(coefficient['odds_ratio']):.2f} ({float(coefficient['odds_ratio_ci_lower']):.2f}, {float(coefficient['odds_ratio_ci_upper']):.2f}) \\
Standardized Australian probability, \% (95\% CI) & {float(contrast['au_standardized_probability'])*100:.1f} ({float(contrast['au_ci_lower'])*100:.1f}, {float(contrast['au_ci_upper'])*100:.1f}) \\
Standardized New Zealand probability, \% (95\% CI) & {float(contrast['nz_standardized_probability'])*100:.1f} ({float(contrast['nz_ci_lower'])*100:.1f}, {float(contrast['nz_ci_upper'])*100:.1f}) \\
Adjusted AU-minus-NZ difference, pp (95\% CI) & {float(contrast['au_minus_nz_probability_contrast'])*100:.1f} ({float(contrast['contrast_ci_lower'])*100:.1f}, {float(contrast['contrast_ci_upper'])*100:.1f}) \\
Destination test & {p_format(coefficient['p_value'])} \\
\bottomrule
\end{{tabular}}
\parbox{{0.94\textwidth}}{{\scriptsize Notes: New Zealand is the reference destination. The model uses origin-country fixed effects and country-cluster-robust CR1 standard errors. Standardized probabilities are averaged equally over the retained matched origins. CI denotes confidence interval and pp denotes percentage points.}}
\end{{table}}
"""
    outputs["table"].write_text(table, encoding="utf-8")

    au = float(contrast["au_standardized_probability"]) * 100
    au_lower = float(contrast["au_ci_lower"]) * 100
    au_upper = float(contrast["au_ci_upper"]) * 100
    nz = float(contrast["nz_standardized_probability"]) * 100
    nz_lower = float(contrast["nz_ci_lower"]) * 100
    nz_upper = float(contrast["nz_ci_upper"]) * 100
    difference = float(contrast["au_minus_nz_probability_contrast"]) * 100
    difference_lower = float(contrast["contrast_ci_lower"]) * 100
    difference_upper = float(contrast["contrast_ci_upper"]) * 100
    figure = rf"""% Generated by scripts/generate_article_model_outputs.py. Do not edit.
\begin{{minipage}}[t]{{0.49\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  width=0.88\linewidth, height=5.2cm,
  xmin=65, xmax=90, ymin=0.5, ymax=2.5,
  xlabel={{Approval probability (\%)}},
  ytick={{1,2}}, yticklabels={{{{New Zealand}},{{Australia}}}},
  title={{(a) Destination probabilities}},
  xmajorgrids=true, tick label style={{font=\scriptsize}},
  label style={{font=\scriptsize}}, title style={{font=\small}},
]
\addplot+[only marks, mark=*, blue!75!black, error bars/.cd, x dir=both, x explicit]
  coordinates {{({au:.12g},2) += ({au_upper-au:.12g},0) -= ({au-au_lower:.12g},0)}};
\addplot+[only marks, mark=square*, red!75!black, error bars/.cd, x dir=both, x explicit]
  coordinates {{({nz:.12g},1) += ({nz_upper-nz:.12g},0) -= ({nz-nz_lower:.12g},0)}};
\end{{axis}}
\end{{tikzpicture}}
\end{{minipage}}%
\hfill
\begin{{minipage}}[t]{{0.49\textwidth}}
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  width=0.88\linewidth, height=5.2cm,
  xmin=-2, xmax=18, ymin=0.5, ymax=1.5,
  xlabel={{Difference (percentage points)}},
  ytick={{1}}, yticklabels={{{{AU--NZ}}}},
  title={{(b) Probability contrast}},
  xmajorgrids=true, tick label style={{font=\scriptsize}},
  label style={{font=\scriptsize}}, title style={{font=\small}},
]
\addplot[gray!70, dashed] coordinates {{(0,0.5) (0,1.5)}};
\addplot+[only marks, mark=*, blue!75!black, error bars/.cd, x dir=both, x explicit]
  coordinates {{({difference:.12g},1) += ({difference_upper-difference:.12g},0) -= ({difference-difference_lower:.12g},0)}};
\end{{axis}}
\end{{tikzpicture}}
\end{{minipage}}
"""
    outputs["figure"].write_text(figure, encoding="utf-8")
    return outputs


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()
    outputs = generate_outputs()
    print("Article pooled-model outputs written:")
    for path in outputs.values():
        print(f"- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
