#!/usr/bin/env python3
"""Generate article tables and figures for Methods Sections 5 and 6."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle: return list(csv.DictReader(handle))


def sha256(path: Path) -> str: return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path, module: str) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("module") != module or value.get("status") != "passed": raise ValueError(f"{path}: analysis did not pass")
    for output in value["outputs"]:
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]: raise ValueError(f"{path}: output hash mismatch for {target}")


def latex(value: str) -> str:
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(character, character) for character in value)


def p_format(value: str) -> str:
    number = float(value)
    return "$p<0.001$" if number < 0.001 else f"$p={number:.3f}$"


def q_format(value: str) -> str:
    number = float(value)
    return "$<0.001$" if number < 0.001 else f"{number:.3f}"


def generate_outputs(*, concordance_dir: Path = ROOT / "data/results/concordance", country_dir: Path = ROOT / "data/results/country_tests", manifest_dir: Path = ROOT / "data/results/manifests", table_dir: Path = ROOT / "article/tables", figure_dir: Path = ROOT / "article/figures") -> dict[str, Path]:
    verify_manifest(manifest_dir / "05_concordance.json", "src.analysis_05_concordance")
    verify_manifest(manifest_dir / "06_country_differences.json", "src.analysis_06_country_differences")
    concordance = rows(concordance_dir / "approval_rate_concordance.csv")
    points = rows(concordance_dir / "approval_rate_scatter_points.csv")
    effects = rows(country_dir / "country_specific_effects_and_tests.csv")
    summary = {row["metric"]: row["value"] for row in rows(country_dir / "country_test_summary.csv")}
    selected = sorted((row for row in rows(country_dir / "forest_plot_selection.csv") if row["displayed"] == "1"), key=lambda row: int(row["display_rank"]))
    table_dir.mkdir(parents=True, exist_ok=True); figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {"concordance_table": table_dir / "approval_rate_concordance.tex", "concordance_figure": figure_dir / "approval_rate_concordance.tex", "country_table": table_dir / "country_specific_results.tex", "forest_figure": figure_dir / "country_difference_forest.tex"}

    lines = ["% Generated by scripts/generate_article_concordance_country_outputs.py. Do not edit.", r"\begin{table}[H]", r"\caption{Cross-destination concordance of matched-country approval rates, 2022--2025}", r"\label{tab:approval-rate-concordance}", r"\centering", r"\small", r"\begin{tabular}{lrrrr}", r"\toprule", r"Method & Coefficient & 95\% CI & $n$ & Two-sided $p$ \\", r"\midrule"]
    for row in concordance:
        lines.append(f"{row['method']} & {float(row['coefficient']):.3f} & ({float(row['ci_lower']):.3f}, {float(row['ci_upper']):.3f}) & {row['n']} & {p_format(row['p_value'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    outputs["concordance_table"].write_text("\n".join(lines) + "\n", encoding="utf-8")

    coordinates = " ".join(f"({float(row['nz_approval_rate'])*100:.10g},{float(row['au_approval_rate'])*100:.10g})" for row in points)
    figure = rf"""% Generated by scripts/generate_article_concordance_country_outputs.py. Do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=0.78\textwidth, height=8.0cm,
  xmin=0, xmax=100, ymin=0, ymax=100,
  xlabel={{New Zealand approval rate (\%)}}, ylabel={{Australian approval rate (\%)}},
  axis equal image, grid=major, tick label style={{font=\small}}, label style={{font=\small}},
]
\addplot[gray!70, dashed, thick, domain=0:100] {{x}};
\addplot[only marks, mark=*, mark size=1.5pt, blue!70!black, opacity=0.75] coordinates {{{coordinates}}};
\end{{axis}}
\end{{tikzpicture}}
"""
    outputs["concordance_figure"].write_text(figure, encoding="utf-8")

    selected_effects = sorted((row for row in effects if row["country"] in {item["country"] for item in selected}), key=lambda row: -abs(float(row["rate_difference_au_minus_nz"])))[:10]
    lines = ["% Generated by scripts/generate_article_concordance_country_outputs.py. Do not edit.", r"\begin{table}[H]", r"\caption{Largest displayed country-specific AU-minus-NZ differences among countries with at least 50 decisions in each destination}", r"\label{tab:country-specific-results}", r"\centering", r"\scriptsize", r"\begin{tabular}{lrrrl}", r"\toprule", r"Country & AU $n$ & NZ $n$ & Difference, pp (95\% CI) & BH $q$ \\", r"\midrule"]
    for row in selected_effects:
        difference, lower, upper = (float(row[key]) * 100 for key in ("rate_difference_au_minus_nz", "rate_difference_ci_lower", "rate_difference_ci_upper"))
        lines.append(f"{latex(row['country'])} & {int(row['au_decision_total']):,} & {int(row['nz_decision_total']):,} & {difference:.1f} ({lower:.1f}, {upper:.1f}) & {q_format(row['bh_q_value'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", rf"\parbox{{0.94\textwidth}}{{\scriptsize Notes: The complete table contains all {summary['countries_tested']} matched countries. Difference is Australia minus New Zealand. BH denotes the Benjamini--Hochberg adjusted $q$-value.}}", r"\end{table}"]
    outputs["country_table"].write_text("\n".join(lines) + "\n", encoding="utf-8")

    forest_rows = sorted(selected, key=lambda row: float(row["rate_difference_au_minus_nz"]))
    labels = ",".join("{" + latex(row["country"]) + "}" for row in forest_rows)
    coordinates = " ".join(f"({float(row['rate_difference_au_minus_nz'])*100:.10g},{index}) += ({(float(row['rate_difference_ci_upper'])-float(row['rate_difference_au_minus_nz']))*100:.10g},0) -= ({(float(row['rate_difference_au_minus_nz'])-float(row['rate_difference_ci_lower']))*100:.10g},0)" for index, row in enumerate(forest_rows, start=1))
    figure = rf"""% Generated by scripts/generate_article_concordance_country_outputs.py. Do not edit.
\begin{{tikzpicture}}
\begin{{axis}}[
  width=0.84\textwidth, height=12.0cm,
  xmin=-35, xmax=70, ymin=0.3, ymax={len(forest_rows)+0.7},
  xlabel={{AU-minus-NZ approval-rate difference (percentage points)}},
  ytick={{{','.join(str(i) for i in range(1, len(forest_rows)+1))}}}, yticklabels={{{labels}}},
  y tick label style={{font=\scriptsize}}, tick label style={{font=\small}}, label style={{font=\small}},
  xmajorgrids=true,
]
\addplot[gray!70, dashed, thick, domain=0.3:{len(forest_rows)+0.7}] (0,x);
\addplot+[only marks, mark=*, blue!75!black, error bars/.cd, x dir=both, x explicit] coordinates {{{coordinates}}};
\end{{axis}}
\end{{tikzpicture}}
"""
    outputs["forest_figure"].write_text(figure, encoding="utf-8")
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__); parser.parse_args()
    outputs = generate_outputs()
    print("Article outputs written:")
    for path in outputs.values(): print(f"- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__": raise SystemExit(main())
