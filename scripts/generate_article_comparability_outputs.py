#!/usr/bin/env python3
"""Generate Step 11 publication tables and figure from verified results."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames:
            raise ValueError(f"{path}: missing CSV header")
        return list(reader)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_manifest(path: Path) -> None:
    value = json.loads(path.read_text(encoding="utf-8"))
    if (
        value.get("module") != "src.analysis_11_comparability"
        or value.get("status") != "passed"
    ):
        raise ValueError(f"{path}: analysis did not pass")
    for output in value.get("outputs", []):
        target = ROOT / output["path"]
        if not target.exists() or sha256(target) != output["sha256"]:
            raise ValueError(f"{path}: output hash mismatch for {target}")


def require_columns(path: Path, source: list[dict[str, str]], required: set[str]) -> None:
    available = set(source[0]) if source else set()
    missing = required - available
    if missing:
        raise ValueError(f"{path}: missing columns {sorted(missing)}")


def label(row: dict[str, str]) -> str:
    return "Pooled" if row["scope"] == "pooled" else row["year"]


def generate_outputs(
    *,
    validation_dir: Path = ROOT / "data/results/validation",
    manifest_dir: Path = ROOT / "data/results/manifests",
    table_dir: Path = ROOT / "article/tables",
    figure_dir: Path = ROOT / "article/figures",
) -> dict[str, Path]:
    verify_manifest(manifest_dir / "11_comparability.json")
    coverage_path = validation_dir / "pairwise_coverage_summary.csv"
    coverage = rows(coverage_path)
    require_columns(
        coverage_path,
        coverage,
        {
            "scope", "year", "union_origins", "matched_origins",
            "unmatched_origins", "au_only_origins", "nz_only_origins",
            "matched_share",
        },
    )
    if len(coverage) != 5 or sum(row["scope"] == "pooled" for row in coverage) != 1:
        raise ValueError(f"{coverage_path}: expected one pooled and four annual rows")
    table_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        "coverage_table": table_dir / "comparability_coverage.tex",
        "figure": figure_dir / "comparability_audit.tex",
    }

    coverage_lines = [
        "% Generated by scripts/generate_article_comparability_outputs.py. Do not edit.",
        r"\begin{table}", r"\caption{Observed origin-country overlap used by the comparability gate}",
        r"\label{tab:comparability-coverage}", r"\centering", r"\small",
        r"\begin{tabular}{lrrrrrr}", r"\toprule",
        r"Period & Union & Matched & Unmatched & AU only & NZ only & Matched share \\",
        r"\midrule",
    ]
    for row in coverage:
        coverage_lines.append(
            f"{label(row)} & {int(row['union_origins'])} & {int(row['matched_origins'])} & "
            f"{int(row['unmatched_origins'])} & {int(row['au_only_origins'])} & "
            f"{int(row['nz_only_origins'])} & {float(row['matched_share']) * 100:.1f}\\% " + r"\\"
        )
    coverage_lines += [
        r"\bottomrule", r"\end{tabular}",
        r"\parbox{0.94\textwidth}{\scriptsize Notes: Union is the number of distinct origins observed in at least one destination. Matched origins are observed in both destinations with positive decision totals. Unmatched origins are retained for destination-specific analyses but excluded from paired analyses. They are not assigned zero decisions in the absent destination.}",
        r"\end{table}",
    ]
    outputs["coverage_table"].write_text("\n".join(coverage_lines) + "\n", encoding="utf-8")

    xlabels = ",".join(label(row) for row in coverage)
    matched = " ".join(f"({label(row)},{float(row['matched_share']) * 100:.12g})" for row in coverage)
    au_only = " ".join(f"({label(row)},{row['au_only_origins']})" for row in coverage)
    nz_only = " ".join(f"({label(row)},{row['nz_only_origins']})" for row in coverage)
    figure = rf"""% Generated by scripts/generate_article_comparability_outputs.py. Do not edit.
\resizebox{{\textwidth}}{{!}}{{%
\begin{{tikzpicture}}
\begin{{groupplot}}[
  group style={{group size=2 by 1,horizontal sep=1.65cm}},
  width=0.43\textwidth,height=5.8cm,
  symbolic x coords={{{xlabels}}},xtick=data,
  tick label style={{font=\scriptsize}},label style={{font=\small}},title style={{font=\small}},
  x tick label style={{rotate=30,anchor=east}},ymajorgrids=true,
]
\nextgroupplot[ybar,bar width=15pt,ymin=0,ymax=100,ylabel={{Matched share (\%)}},title={{(a) Common-origin coverage}},nodes near coords,nodes near coords style={{font=\scriptsize,/pgf/number format/fixed,/pgf/number format/fixed zerofill,/pgf/number format/precision=1}}]
\addplot[fill=blue!55,draw=blue!80!black] coordinates {{{matched}}};
\nextgroupplot[ybar stacked,bar width=15pt,ymin=0,ylabel={{Destination-only origins}},title={{(b) Unmatched-origin decomposition}},legend columns=2,legend style={{font=\scriptsize,draw=none,at={{(0.5,-0.34)}},anchor=north}}]
\addplot[fill=blue!55,draw=blue!80!black] coordinates {{{au_only}}};\addlegendentry{{AU only}}
\addplot[fill=red!55,draw=red!80!black] coordinates {{{nz_only}}};\addlegendentry{{NZ only}}
\end{{groupplot}}
\end{{tikzpicture}}%
}}
"""
    outputs["figure"].write_text(figure, encoding="utf-8")
    return outputs


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validation-dir", type=Path, default=ROOT / "data/results/validation")
    parser.add_argument("--manifest-dir", type=Path, default=ROOT / "data/results/manifests")
    parser.add_argument("--table-dir", type=Path, default=ROOT / "article/tables")
    parser.add_argument("--figure-dir", type=Path, default=ROOT / "article/figures")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    outputs = generate_outputs(
        validation_dir=args.validation_dir,
        manifest_dir=args.manifest_dir,
        table_dir=args.table_dir,
        figure_dir=args.figure_dir,
    )
    print("Comparability publication artifacts written:")
    for path in outputs.values():
        print(f"- {path.resolve().relative_to(ROOT)}")


if __name__ == "__main__":
    main()
