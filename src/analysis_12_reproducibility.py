"""Consolidate reproducibility metadata and verify registered artifacts (Step 12)."""

from __future__ import annotations

import argparse
import csv
import json
import platform
import subprocess
import sys
from pathlib import Path
from typing import Any

from .analysis_common import (
    PROJECT_ROOT,
    display_path,
    read_json,
    sha256,
    utc_timestamp,
    write_csv,
    write_json,
)


SOURCE_MANIFESTS = (
    "01_analysis_contract.json",
    "02_data_validation_and_tables.json",
    "11_comparability.json",
    "03_descriptive.json",
    "04_matched_comparison.json",
    "05_concordance.json",
    "06_country_differences.json",
    "07_binomial_regression.json",
    "08_origin_composition.json",
    "09_temporal.json",
    "10_sensitivity.json",
)
STOCHASTIC_MODULES = {
    "src.analysis_04_matched_comparison",
    "src.analysis_05_concordance",
    "src.analysis_08_origin_composition",
    "src.analysis_09_temporal",
    "src.analysis_10_sensitivity",
}
ARTIFACT_COLUMNS = [
    "artifact_id", "artifact_type", "path", "sha256", "size_bytes",
    "row_count", "producer", "source_manifest", "status",
]
SOFTWARE_COLUMNS = ["component", "version", "required", "status"]
ISSUE_COLUMNS = ["source", "check", "status", "message"]


def csv_row_count(path: Path) -> int | str:
    if path.suffix.lower() != ".csv":
        return ""
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.reader(handle)
        try:
            next(reader)
        except StopIteration:
            return 0
        return sum(1 for _ in reader)


def command_version(command: list[str]) -> str:
    try:
        completed = subprocess.run(
            command, check=False, capture_output=True, text=True, timeout=15
        )
    except (OSError, subprocess.TimeoutExpired):
        return ""
    text = (completed.stdout or completed.stderr).strip()
    return text.splitlines()[0] if text else ""


def publication_producer(path: Path) -> str:
    source = path if path.suffix == ".tex" else path.with_suffix(".tex")
    if not source.exists():
        return ""
    first = source.read_text(encoding="utf-8").splitlines()[0]
    prefix = "% Generated by "
    return first[len(prefix):].split(".", 1)[0] if first.startswith(prefix) else ""


def run(
    *,
    manifest_dir: Path,
    table_dir: Path,
    figure_dir: Path,
    project_root: Path = PROJECT_ROOT,
) -> dict[str, Path]:
    issues: list[dict[str, str]] = []
    artifacts: list[dict[str, Any]] = []
    source_records: list[dict[str, Any]] = []

    for manifest_name in SOURCE_MANIFESTS:
        manifest_path = manifest_dir / manifest_name
        if not manifest_path.exists():
            raise ValueError(f"{manifest_path}: required manifest is missing")
        manifest = read_json(manifest_path)
        module = str(manifest.get("module", ""))
        if manifest.get("status") != "passed":
            raise ValueError(f"{manifest_path}: source analysis did not pass")
        if not manifest.get("analysis_timestamp_utc"):
            issues.append({"source": manifest_name, "check": "timestamp", "status": "failed", "message": "analysis timestamp is missing"})
        inputs = manifest.get("inputs")
        if not isinstance(inputs, list) or not inputs:
            issues.append({"source": manifest_name, "check": "inputs", "status": "failed", "message": "input records are missing"})
        else:
            for item in inputs:
                if not item.get("path") or not item.get("sha256"):
                    issues.append({"source": manifest_name, "check": "input_hash", "status": "failed", "message": "an input lacks path or SHA-256"})
        configuration_recorded = bool(manifest.get("configuration") or manifest.get("methods")) or bool(manifest.get("config_file") and manifest.get("config_sha256")) or any(str(item.get("path", "")).endswith("analysis_config.json") for item in inputs or [])
        if not configuration_recorded:
            issues.append({"source": manifest_name, "check": "configuration", "status": "failed", "message": "method or configuration metadata are missing"})
        if module in STOCHASTIC_MODULES:
            configuration = manifest.get("configuration", {})
            has_seed = "bootstrap_seed" in configuration or "bootstrap_seed_rule" in configuration
            if not has_seed:
                issues.append({"source": manifest_name, "check": "random_seed", "status": "failed", "message": "stochastic module does not record its seed"})

        outputs = manifest.get("outputs")
        if not isinstance(outputs, list) or not outputs:
            raise ValueError(f"{manifest_path}: no registered outputs")
        for index, output in enumerate(outputs, start=1):
            relative = str(output.get("path", ""))
            expected_hash = str(output.get("sha256", ""))
            target = project_root / relative
            if not relative or not expected_hash or not target.exists():
                raise ValueError(f"{manifest_path}: incomplete or missing output {index}")
            current_hash = sha256(target)
            if current_hash != expected_hash:
                raise ValueError(f"{manifest_path}: output hash mismatch for {target}")
            artifact_id = str(output.get("name") or output.get("artifact") or f"output_{index}")
            artifacts.append(
                {
                    "artifact_id": f"{module}:{artifact_id}",
                    "artifact_type": "numerical_result" if target.suffix == ".csv" else "analysis_artifact",
                    "path": relative,
                    "sha256": current_hash,
                    "size_bytes": target.stat().st_size,
                    "row_count": output.get("rows", csv_row_count(target)),
                    "producer": module,
                    "source_manifest": display_path(manifest_path, project_root),
                    "status": "verified",
                }
            )
        warning_recorded = module != "src.analysis_07_binomial_regression" or any(str(output.get("name") or output.get("artifact")) == "diagnostics" for output in outputs)
        if not warning_recorded:
            issues.append({"source": manifest_name, "check": "warnings", "status": "failed", "message": "model warning diagnostics are not registered"})
        source_records.append(
            {
                "module": module,
                "manifest": display_path(manifest_path, project_root),
                "manifest_sha256": sha256(manifest_path),
                "analysis_timestamp_utc": manifest["analysis_timestamp_utc"],
                "outputs": len(outputs),
                "configuration_recorded": configuration_recorded,
                "warning_recorded_or_not_applicable": warning_recorded,
            }
        )

    publication_paths = sorted(table_dir.glob("*.tex")) + sorted(figure_dir.glob("*.tex"))
    publication_paths += sorted(figure_dir.glob("*.pdf")) + sorted(figure_dir.glob("*.png"))
    for path in publication_paths:
        producer = publication_producer(path)
        if not producer:
            issues.append({"source": display_path(path, project_root), "check": "producer", "status": "failed", "message": "publication artifact has no generated-source marker"})
        artifacts.append(
            {
                "artifact_id": f"publication:{path.stem}:{path.suffix[1:]}",
                "artifact_type": "publication_table" if path.parent == table_dir else "publication_figure",
                "path": display_path(path, project_root),
                "sha256": sha256(path),
                "size_bytes": path.stat().st_size,
                "row_count": "",
                "producer": producer,
                "source_manifest": "",
                "status": "verified" if producer else "failed",
            }
        )

    if issues:
        failing = [row for row in issues if row["status"] == "failed"]
        if failing:
            issue_path = manifest_dir / "reproducibility_issues.csv"
            write_csv(issue_path, ISSUE_COLUMNS, issues)
            raise ValueError(f"reproducibility audit found {len(failing)} issue(s)")

    software = [
        {"component": "Python", "version": platform.python_version(), "required": "true", "status": "recorded"},
        {"component": "Operating system", "version": platform.platform(), "required": "true", "status": "recorded"},
        {"component": "Rscript", "version": command_version(["Rscript", "--version"]), "required": "true", "status": ""},
        {"component": "pdfTeX", "version": command_version(["pdflatex", "--version"]), "required": "false", "status": ""},
        {"component": "latexmk", "version": command_version(["latexmk", "--version"]), "required": "false", "status": ""},
    ]
    for row in software:
        if not row["status"]:
            row["status"] = "recorded" if row["version"] else "unavailable"
        if row["required"] == "true" and row["status"] != "recorded":
            raise ValueError(f"required software version unavailable: {row['component']}")

    artifacts.sort(key=lambda row: (row["artifact_type"], row["path"]))
    artifact_path = manifest_dir / "artifact_manifest.csv"
    software_path = manifest_dir / "software_versions.csv"
    pipeline_path = manifest_dir / "pipeline_run.json"
    issue_path = manifest_dir / "reproducibility_issues.csv"
    write_csv(artifact_path, ARTIFACT_COLUMNS, artifacts)
    write_csv(software_path, SOFTWARE_COLUMNS, software)
    write_csv(issue_path, ISSUE_COLUMNS, [])
    write_json(
        pipeline_path,
        {
            "status": "passed",
            "analysis_timestamp_utc": utc_timestamp(),
            "source_manifest_count": len(source_records),
            "registered_artifact_count": len(artifacts),
            "reproducibility_issue_count": 0,
            "source_manifests": source_records,
            "python_executable": sys.executable,
        },
    )
    outputs = {
        "artifact_manifest": artifact_path,
        "software_versions": software_path,
        "pipeline_run": pipeline_path,
        "reproducibility_issues": issue_path,
    }
    manifest_path = manifest_dir / "12_reproducibility.json"
    write_json(
        manifest_path,
        {
            "module": "src.analysis_12_reproducibility",
            "status": "passed",
            "analysis_timestamp_utc": utc_timestamp(),
            "inputs": [
                {"path": row["manifest"], "sha256": row["manifest_sha256"]}
                for row in source_records
            ],
            "outputs": [
                {"name": name, "path": display_path(path, project_root), "sha256": sha256(path), "rows": csv_row_count(path)}
                for name, path in outputs.items()
            ],
            "summary": {"source_manifests": len(source_records), "registered_artifacts": len(artifacts), "reproducibility_issues": 0},
        },
    )
    outputs["manifest"] = manifest_path
    return outputs


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest-dir", type=Path, default=PROJECT_ROOT / "data/results/manifests")
    parser.add_argument("--table-dir", type=Path, default=PROJECT_ROOT / "article/tables")
    parser.add_argument("--figure-dir", type=Path, default=PROJECT_ROOT / "article/figures")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    outputs = run(manifest_dir=args.manifest_dir, table_dir=args.table_dir, figure_dir=args.figure_dir)
    print("Reproducibility artifacts written:")
    for path in outputs.values():
        print(f"- {display_path(path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
